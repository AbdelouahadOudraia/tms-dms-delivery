import {test} from 'node:test';
import assert from 'node:assert/strict';
import {once} from 'node:events';
import {mkdtempSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve,dirname,basename} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import type {AddressInfo} from 'node:net';
import {createSalesApi} from '../server/sales/api';
import {CompanyDirectory} from '../server/sales/companies';
import {verifiedFixture} from './support/legacyAccounts';

test('e-mail exclusif : comptes historiques conservés, vérification obligatoire et isolation en démo',async t=>{
  const parent=resolve(tmpdir()),root=mkdtempSync(join(parent,'tms-email-only-')),previous=process.env.NODE_ENV;
  process.env.NODE_ENV='development';
  const api=createSalesApi(root,undefined,'demo'),file=join(root,'.data','demo','demo.sqlite');
  const directory=new CompanyDirectory(file,true,true),db=new DatabaseSync(file);
  directory.setup('preserved-admin-password');verifiedFixture(directory,'admin','owner@demo.test');
  directory.create('Electroplanet fictive','electroplanet','preserved-company-password');
  verifiedFixture(directory,'electroplanet','logistics@demo.test');
  directory.create('Témoin','witness','preserved-witness-password');verifiedFixture(directory,'witness');
  directory.saveTransport('electroplanet',0,{marker:'electroplanet-preserved'});
  directory.saveTransport('witness',0,{marker:'witness-preserved'});
  const original=db.prepare('SELECT login,password,company,email_login FROM accounts ORDER BY login').all();
  assert.ok(original.every(row=>row.email_login===0),'The legacy flag cannot permit username authentication');
  const http=api.app.listen(0,'127.0.0.1');await once(http,'listening');
  t.after(async()=>{
    await new Promise<void>(done=>http.close(()=>done()));api.close();directory.close();db.close();
    assert.equal(existsSync(join(root,'.data','sales-live.sqlite')),false);
    assert.equal(existsSync(join(root,'.data','tenant-test.sqlite')),false);
    if(previous===undefined)delete process.env.NODE_ENV;else process.env.NODE_ENV=previous;
    if(dirname(resolve(root))===parent && basename(root).startsWith('tms-email-only-'))rmSync(root,{recursive:true,force:true});
  });
  const base='http://127.0.0.1:'+(http.address() as AddressInfo).port;
  async function call(method:string,path:string,body?:object,token='',status=200) {
    const response=await fetch(base+path,{method,headers:{'content-type':'application/json',authorization:'Bearer '+token},body:body&&JSON.stringify(body)});
    const data=await response.json();assert.equal(response.status,status,method+' '+path+' '+JSON.stringify(data));return data;
  }
  const login=(email:string,password:string,status=200)=>call('POST','/login',{login:email,password},'',status);
  const refusal=await login('admin','preserved-admin-password',401);
  assert.deepEqual(await login('electroplanet','preserved-company-password',401),refusal);
  assert.deepEqual(await login('unknown@demo.test','preserved-company-password',401),refusal);
  assert.deepEqual(await login('logistics@demo.test','incorrect-password',401),refusal);
  assert.deepEqual(await login('not-an-email','preserved-admin-password',401),refusal);
  await call('POST','/login',{},'',401);
  const admin=(await login(' OWNER@DEMO.TEST ','preserved-admin-password')).token;
  const company=(await login('logistics@demo.test','preserved-company-password')).token;
  const witness=(await login('witness@fixture.test','preserved-witness-password')).token;
  assert.equal((await call('GET','/access',undefined,admin)).account.role,'admin');
  assert.equal((await call('GET','/access',undefined,company)).account.role,'company');
  await call('GET','/admin/overview',undefined,company,403);
  await call('GET','/companies/witness/transport',undefined,company,403);
  assert.deepEqual((await call('GET','/companies/electroplanet/transport',undefined,company)).data,{marker:'electroplanet-preserved'});
  await call('POST','/companies',{name:'Sans e-mail'},admin,400);
  assert.equal(db.prepare("SELECT 1 FROM companies WHERE id='sans-e-mail'").get(),undefined);
  assert.deepEqual(db.prepare('SELECT login,password,company,email_login FROM accounts ORDER BY login').all(),original);
  await call('PUT','/companies/electroplanet/email',{email:'changed@demo.test',currentPassword:'preserved-admin-password'},admin);
  await call('GET','/companies/electroplanet/transport',undefined,company);
  await login('changed@demo.test','preserved-company-password',401);
  await login('logistics@demo.test','preserved-company-password');
  const waiting=(await call('GET','/admin/overview',undefined,admin)).accounts.find(account=>account.login==='electroplanet');
  assert.equal(waiting.email,'logistics@demo.test');assert.equal(waiting.pendingEmail,'changed@demo.test');assert.equal(waiting.emailVerified,true);
  await call('POST','/company-email/request',{email:'changed@demo.test'},'',202);
  assert.deepEqual(await call('GET','/demo/messages'),[]);
  await call('POST','/companies/electroplanet/email/verification',{},admin);
  const messages=await call('GET','/demo/messages');
  await call('POST','/company-email/verify',{token:messages[0].link.split('/').pop()});
  await call('GET','/companies/electroplanet/transport',undefined,company,401);
  await login('logistics@demo.test','preserved-company-password',401);
  const changed=(await login('changed@demo.test','preserved-company-password')).token;
  await login('electroplanet','preserved-company-password',401);
  await call('PUT','/companies/electroplanet/status',{status:'disabled'},admin);
  await login('changed@demo.test','preserved-company-password',403);
  await call('GET','/companies/electroplanet/transport',undefined,changed,401);
  assert.deepEqual((await call('GET','/companies/witness/transport',undefined,witness)).data,{marker:'witness-preserved'});
  db.prepare("UPDATE company_emails SET verified_at=NULL WHERE login='admin'").run();
  await call('GET','/admin/overview',undefined,admin,401);
  await login('owner@demo.test','preserved-admin-password',401);
  assert.deepEqual(db.prepare('SELECT login,password,company,email_login FROM accounts ORDER BY login').all(),original);
  assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
});
